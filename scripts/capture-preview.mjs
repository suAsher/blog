import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

await mkdir('docs/qa', { recursive: true });
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const base = 'http://127.0.0.1:4321';
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.goto(base, { waitUntil: 'networkidle' });
await page.screenshot({ path: 'docs/qa/home-desktop.png', fullPage: true });
await page.goto(base + '/articles/build-a-learning-system/', { waitUntil: 'networkidle' });
await page.screenshot({ path: 'docs/qa/article-desktop.png' });
await page.locator('#article-body h2').first().scrollIntoViewIfNeeded();
await page.evaluate(() => window.scrollBy({ top: 220, behavior: 'instant' }));
await page.screenshot({ path: 'docs/qa/article-reading.png' });
await page.evaluate(() => { document.documentElement.dataset.theme = 'light'; });
await page.screenshot({ path: 'docs/qa/article-light.png' });
await page.evaluate(() => { document.documentElement.dataset.theme = 'dark'; });
await page.goto(base + '/articles/?q=没有这篇文章2026', { waitUntil: 'networkidle' });
await page.getByRole('heading', { name: '还没有找到这片叶子' }).waitFor();
await page.screenshot({ path: 'docs/qa/search-empty.png' });
await page.setViewportSize({ width: 768, height: 1024 });
await page.goto(base, { waitUntil: 'networkidle' });
await page.screenshot({ path: 'docs/qa/home-tablet.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(base, { waitUntil: 'networkidle' });
await page.screenshot({ path: 'docs/qa/home-mobile.png', fullPage: true });
await page.goto(base + '/articles/build-a-learning-system/', { waitUntil: 'networkidle' });
await page.screenshot({ path: 'docs/qa/article-mobile.png' });
console.log(JSON.stringify({ screenshots: 8, mobile: { viewport: await page.evaluate(() => document.documentElement.clientWidth), scroll: await page.evaluate(() => document.documentElement.scrollWidth) } }));
await browser.close();
